import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import * as XLSX from 'xlsx';
const browser = await chromium.launch({channel:'msedge', headless:true});
const context = await browser.newContext({viewport:{width:1440,height:1000}, acceptDownloads:true});
const user = {id:1,name:'Test Admin',fullName:'Test Admin',role:'Super Admin',permissions:['*']};
const employees = [{id:'CHECK-01',name:'Attendance One',department:'Engineering',salary:324000,status:'Active'}, {id:'CHECK-02',name:'Attendance Two',department:'Engineering',salary:360000,status:'Active'}];
let records = [];
let failSecond = false;
await context.route('**/api/**', async route => {
  const path = new URL(route.request().url()).pathname.replace(/^\/api/,'');
  let data = [];
  if(path === '/health') data = {ok:true,db:'connected'};
  else if(path === '/auth/me') data = {user};
  else if(path.includes('profile')) data = {profile:user,user};
  else if(path === '/settings/workspace/organization') data = {organization:{name:'Bangalore Electronics',address:'123 Test Road',city:'Bengaluru',state:'Karnataka',pincode:'560001'}};
  else if(path === '/hrms/employees') data = {employees};
  else if(path === '/hrms/attendance') {
    if(route.request().method() === 'POST') {
      const row = route.request().postDataJSON();
      if (failSecond && row.employeeId === 'CHECK-02') return route.fulfill({status:400,json:{error:'Test save failure'}});
      records = records.filter(r => !(r.employeeId === row.employeeId && r.month === row.month));
      const saved = {...row, id:row.employeeId, savedAt:new Date().toISOString()}; records.push(saved);
      data = {attendanceRecord:saved};
    } else data = {attendance:records};
  } else if(path === '/hrms/salaries') data = {salaries:[{id:1,employeeId:'CHECK-01',employeeName:'Attendance One',month:'February 2026',department:'Engineering',salary:324000,workingDays:28,unpaidDays:1.5,lopAmount:1446.43,pfAmount:0}]};
  await route.fulfill({json:data});
});
const page = await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await mkdir('artifacts/hrms-check',{recursive:true});
try {
  await page.goto('http://localhost:5173/attendance');
  await page.getByRole('button',{name:'Save All Attendance',exact:true}).waitFor();
  await page.getByLabel('Attendance month').fill('2026-02');
  await page.getByLabel('Attendance One, day 1',{exact:true}).selectOption('H');
  await page.getByLabel('Attendance One, day 2',{exact:true}).selectOption('A');
  await page.getByLabel('Attendance Two, day 3',{exact:true}).selectOption('L');
  assert.equal(await page.getByRole('button',{name:'Download Excel'}).isDisabled(),true);
  await page.getByRole('button',{name:'Save All Attendance',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Attendance saved for all 2 employees.'}).waitFor();
  assert.equal(records.length,2); assert.equal(records[0].statuses.length,28);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'Download Excel'}).click();
  const download = await downloadPromise;
  await download.saveAs('artifacts/hrms-check/attendance.xlsx');
  const book = XLSX.read(await readFile('artifacts/hrms-check/attendance.xlsx'), {type:'buffer'});
  const rows = XLSX.utils.sheet_to_json(book.Sheets[book.SheetNames[0]],{header:1});
  assert.deepEqual(rows[1].slice(-8),[26,1,0,1,0,28,26.5,1.5]);
  await page.reload(); await page.getByLabel('Attendance month').fill('2026-02');
  await page.waitForFunction(()=>document.querySelector('select[aria-label="Attendance One, day 1"]')?.value === 'H');
  await page.screenshot({path:'artifacts/hrms-check/attendance.png'});
  await page.getByLabel('Attendance One, day 4',{exact:true}).selectOption('L');
  await page.getByLabel('Attendance Two, day 4',{exact:true}).selectOption('H');
  failSecond = true;
  await page.getByRole('button',{name:'Save All Attendance',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'1 of 2 employees saved.'}).waitFor();
  assert.equal(await page.getByLabel('Attendance Two, day 4',{exact:true}).inputValue(),'H');
  assert.equal(await page.getByRole('button',{name:'Download Excel'}).isDisabled(),true);
  failSecond = false;
  await page.getByRole('button',{name:'Save All Attendance',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Attendance saved for all 2 employees.'}).waitFor();
  await page.goto('http://localhost:5173/reviews');
  await page.getByRole('heading',{name:'Review Register',exact:true}).waitFor();
  assert.equal(await page.getByRole('heading',{name:'KPI / Performance Metrics'}).count(),0);
  await page.getByRole('heading',{name:'Salary Reassessment',exact:true}).waitFor();
  await page.goto('http://localhost:5173/payroll');
  await page.getByRole('columnheader',{name:'Annual Gross',exact:true}).waitFor();
  assert.equal(await page.getByRole('columnheader',{name:'Status',exact:true}).count(),0);
  await page.goto('http://localhost:5173/payslip');
  await page.locator('input[type="month"]').fill('2026-02');
  await page.getByRole('button',{name:'Create Payslip',exact:true}).click();
  await page.locator('#payslip-print-area').getByText('123 Test Road, Bengaluru, Karnataka, 560001',{exact:true}).waitFor();
  const text=await page.locator('#payslip-print-area').innerText();
  assert.ok(!text.includes('Payroll Status') && !text.includes('Payroll Ref'));
  assert.ok(text.includes('26.5'));
  await page.emulateMedia({media:'print'});
  await page.setViewportSize({width:794,height:1123});
  await page.pdf({path:'artifacts/hrms-check/payslip.pdf',format:'A4',printBackground:true,displayHeaderFooter:true,preferCSSPageSize:true});
  await page.screenshot({path:'artifacts/hrms-check/payslip.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: all-employee save/reload, Excel download and totals, review sections, payroll columns, company address and payslip print render.');
} finally {await browser.close();}
